// Flattened Dictionary: { DepartmentName: [Programs...] }
export const ACADEMIC_CATALOG = {};
Object.values(FACULTY_CATALOG).forEach(depts => {
  Object.entries(depts).forEach(([deptName, progs]) => {
    ACADEMIC_CATALOG[deptName] = progs;
  });
});

export const FACULTIES = Object.keys(FACULTY_CATALOG);
export const DEPARTMENTS = Object.keys(ACADEMIC_CATALOG);

export const getDepartmentsForFaculty = (facultyName) => {
  return Object.keys(FACULTY_CATALOG[facultyName] || {});
};

export const getProgramsForDepartment = (deptName) => {
  return ACADEMIC_CATALOG[deptName] || [];
};

export const getProgramsForFaculty = (facultyName) => {
  if (!facultyName || !FACULTY_CATALOG[facultyName]) return [];
  const progs = [];
  Object.values(FACULTY_CATALOG[facultyName]).forEach(list => progs.push(...list));
  return Array.from(new Set(progs));
};

export const findDepartmentAndFacultyForProgram = (programName) => {
  if (!programName || typeof programName !== 'string') return null;
  const rawTarget = programName.trim().toLowerCase();
  if (!rawTarget) return null;

  // 1. Exact match
  for (const [faculty, depts] of Object.entries(FACULTY_CATALOG)) {
    for (const [dept, progs] of Object.entries(depts)) {
      const matched = progs.find(p => p.trim().toLowerCase() === rawTarget);
      if (matched) {
        return { faculty, department: dept, program: matched };
      }
    }
  }

  // 2. Normalized match (clean degree prefixes like BS, MS, PhD)
  const clean = (s) => s.replace(/^(bs|b\.sc\.|m\.phil|ms|ph\.d|diploma in)\s+/i, '').replace(/[^a-z0-9]/g, '');
  const cleanTarget = clean(rawTarget);
  if (cleanTarget.length >= 4) {
    for (const [faculty, depts] of Object.entries(FACULTY_CATALOG)) {
      for (const [dept, progs] of Object.entries(depts)) {
        for (const p of progs) {
          if (clean(p.toLowerCase()) === cleanTarget) {
            return { faculty, department: dept, program: p };
          }
        }
      }
    }
  }

  // 3. Substring inclusion
  for (const [faculty, depts] of Object.entries(FACULTY_CATALOG)) {
    for (const [dept, progs] of Object.entries(depts)) {
      for (const p of progs) {
        const pLower = p.trim().toLowerCase();
        if (pLower.includes(rawTarget) || rawTarget.includes(pLower)) {
          return { faculty, department: dept, program: p };
        }
      }
    }
  }

  return null;
};

export const findFacultyForDepartment = (deptName) => {
  if (!deptName || typeof deptName !== 'string') return null;
  const rawTarget = deptName.trim().toLowerCase();
  if (!rawTarget) return null;

  for (const [faculty, depts] of Object.entries(FACULTY_CATALOG)) {
    for (const dept of Object.keys(depts)) {
      if (dept.trim().toLowerCase() === rawTarget) {
        return faculty;
      }
    }
  }

  for (const [faculty, depts] of Object.entries(FACULTY_CATALOG)) {
    for (const dept of Object.keys(depts)) {
      const dLower = dept.trim().toLowerCase();
      if (dLower.includes(rawTarget) || rawTarget.includes(dLower)) {
        return faculty;
      }
    }
  }

  return null;
};

export const getAllPrograms = () => {
  const all = [];
  Object.values(ACADEMIC_CATALOG).forEach(progs => all.push(...progs));
  return Array.from(new Set(all));
};

/**
 * Validates whether a given user is eligible to register for an event.
 * @param {Object} user Current logged-in user profile
 * @param {Object} event Event object
 * @returns {{ eligible: boolean, reason: string, missingProfile: boolean }}
 */
export const checkEventEligibility = (user, event) => {
  if (!event || event.eligibility_type !== 'restricted') {
    return { eligible: true, reason: '', missingProfile: false };
  }

  // Non-student staff roles bypass eligibility restrictions for operational reasons
  const staffRoles = ['admin', 'advisor', 'head_advisor', 'president'];
  if (user && staffRoles.includes(user.role)) {
    return { eligible: true, reason: 'Staff access', missingProfile: false };
  }

  if (!user) {
    return {
      eligible: false,
      reason: 'Please log in to verify your eligibility for this restricted event.',
      missingProfile: false
    };
  }

  const studentDept = (user.department || '').trim().toLowerCase();
  const studentProg = (user.program || '').trim().toLowerCase();

  if (!studentDept && !studentProg) {
    return {
      eligible: false,
      reason: 'Your profile does not specify your Department or Degree Program.',
      missingProfile: true
    };
  }

  const allowedDepts = Array.isArray(event.allowed_departments) ? event.allowed_departments : [];
  const allowedProgs = Array.isArray(event.allowed_programs) ? event.allowed_programs : [];

  // Check Department
  if (allowedDepts.length > 0) {
    if (!studentDept) {
      return {
        eligible: false,
        reason: 'Your profile is missing department details.',
        missingProfile: true
      };
    }
    const deptMatch = allowedDepts.some(d => {
      const target = d.trim().toLowerCase();
      return studentDept.includes(target) || target.includes(studentDept);
    });
    if (!deptMatch) {
      return {
        eligible: false,
        reason: `Exclusively restricted to: ${allowedDepts.join(', ')}.`,
        missingProfile: false
      };
    }
  }

  // Check Degree Program
  if (allowedProgs.length > 0) {
    if (!studentProg) {
      return {
        eligible: false,
        reason: 'Your profile is missing degree program details.',
        missingProfile: true
      };
    }
    const progMatch = allowedProgs.some(p => {
      const target = p.trim().toLowerCase();
      return studentProg.includes(target) || target.includes(studentProg);
    });
    if (!progMatch) {
      return {
        eligible: false,
        reason: `Restricted to students enrolled in: ${allowedProgs.join(', ')}.`,
        missingProfile: false
      };
    }
  }

  return { eligible: true, reason: '', missingProfile: false };
};
